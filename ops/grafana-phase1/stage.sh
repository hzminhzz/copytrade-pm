#!/usr/bin/env bash
# Disposable owner-only Grafana Phase 1 verification. Never modifies port 8443.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
COMPOSE=ops/grafana-phase1/compose.yaml
PRIVATE_HOME="$HOME/.local/share/copytrade-grafana-phase1"
SECRETS="$PRIVATE_HOME/private.env"
SOCKET_ROOT=/run/copytrade-grafana-phase1
SOCKET="$SOCKET_ROOT/serve.sock"
VOLUME=copytrade-grafana-phase1_evidence
# The helper has root-equivalent Docker access but mounts only the local
# tailscaled API socket and read-only Tailscale CLI. No sudo secret is used.
tailscale_root() {
  docker run --rm --network none --user 0 \
    --entrypoint /usr/bin/tailscale \
    -v /usr/bin/tailscale:/usr/bin/tailscale:ro \
    -v /var/run/tailscale/tailscaled.sock:/var/run/tailscale/tailscaled.sock \
    busybox:1.37@sha256:a7dbc319b1438115a207e11930dc4bb3e643dcb3ec0bdd694bb36cd8fad289ec "$@"
}
MODE="${1:-status}"

bootstrap() {
  install -d -m 0700 "$PRIVATE_HOME"
  if [ ! -e "$SECRETS" ]; then
    # Extract only one validated identity from prior owner SSO configuration.
    # Never source arbitrary user configuration or print the identity.
    python3 - "$HOME/.config/copytrade-dashboard/private.env" "$SECRETS" <<'PY'
import re,secrets,sys,os,pathlib,subprocess,json
source=pathlib.Path(sys.argv[1]).read_text()
values={}
for line in source.splitlines():
    if "=" in line and not line.lstrip().startswith("#"):
        key,val=line.split("=",1)
        values[key]=val.strip().strip('"').strip("'")
identity=values.get("DASHBOARD_TAILSCALE_USER_LOGIN","")
assert re.fullmatch(r"[A-Za-z0-9._+@-]{2,254}",identity), "OWNER_ID_UNAVAILABLE"
node=json.loads(subprocess.check_output(["tailscale","status","--json"],text=True))
host=node["Self"]["DNSName"].rstrip(".")
assert re.fullmatch(r"[A-Za-z0-9.-]+\.ts\.net",host), "TAILNET_DNS_UNAVAILABLE"
secrets_data={
    "GRAFANA_OWNER_LOGIN":identity,
    "GRAFANA_TAILNET_HOST":host,
    "GRAFANA_PROJECTION_TOKEN":secrets.token_hex(32),
    "GRAFANA_ADMIN_PASSWORD":secrets.token_hex(32)
}
fd=os.open(sys.argv[2],os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
with os.fdopen(fd,"w") as f:
    for k,v in secrets_data.items():
        f.write(f"{k}={v}\n")
print("Staging credentials generated privately (not printed).")
PY
  fi
  # File was generated by code above: only a known, validated set of names and values.
  set -a
  # shellcheck source=/dev/null
  . "$SECRETS"
  set +a
  export GRAFANA_OWNER_LOGIN GRAFANA_TAILNET_HOST GRAFANA_PROJECTION_TOKEN GRAFANA_ADMIN_PASSWORD
}

case "$MODE" in
  start)
    if tailscale serve status 2>/dev/null | grep -q ':8444'; then
      echo "REFUSE: HTTPS 8444 has a preexisting Serve configuration."
      exit 2
    fi
    if [ -e "$SOCKET_ROOT" ]; then
      if [ "$(stat -c '%u:%a' "$SOCKET_ROOT")" != "0:700" ]; then
        echo "REFUSE: untrusted preexisting socket root."
        exit 2
      fi
      if docker exec copytrade-grafana-phase1-ingress-1 test -S /run/staging-ingress/serve.sock >/dev/null 2>&1; then
        echo "REFUSE: existing staging socket; inspect before recreating."
        exit 2
      fi
    fi
    bootstrap
    docker volume create "$VOLUME" >/dev/null
    docker run --rm --network none -v "$VOLUME:/evidence" busybox:1.37@sha256:a7dbc319b1438115a207e11930dc4bb3e643dcb3ec0bdd694bb36cd8fad289ec sh -c 'chown 10002:10002 /evidence; chmod 0755 /evidence'
    if [ ! -d "$SOCKET_ROOT" ]; then
      docker run --rm --network none -v /run:/hostrun busybox:1.37@sha256:a7dbc319b1438115a207e11930dc4bb3e643dcb3ec0bdd694bb36cd8fad289ec sh -c 'mkdir /hostrun/copytrade-grafana-phase1 && chmod 0700 /hostrun/copytrade-grafana-phase1'
    fi
    docker compose -f "$COMPOSE" config --quiet
    docker compose -f "$COMPOSE" up -d --build --wait
    docker exec copytrade-grafana-phase1-ingress-1 test -S /run/staging-ingress/serve.sock || { echo "BLOCKED: isolated Unix socket absent"; exit 3; }
    echo "Isolated Grafana staging healthy, Unix socket available."
    tailscale_root serve --https=8444 --bg "unix:$SOCKET"
    echo "Tailscale Serve 8444 set; 8443 route must remain unchanged."
    ;;
  stop)
    if tailscale serve status 2>/dev/null | grep -q "unix:$SOCKET"; then
      tailscale_root serve --https=8444 off
      echo "Removed only this staging Serve route."
    fi
    if [ -r "$SECRETS" ]; then
      bootstrap
      docker compose -f "$COMPOSE" down --remove-orphans
    else
      echo "No private environment found; refusing to interfere with other stacks."
    fi
    if [ -d "$SOCKET_ROOT" ]; then
      docker run --rm --network none -v /run:/hostrun busybox:1.37@sha256:a7dbc319b1438115a207e11930dc4bb3e643dcb3ec0bdd694bb36cd8fad289ec sh -c 'rm -f /hostrun/copytrade-grafana-phase1/serve.sock; rmdir /hostrun/copytrade-grafana-phase1'
    fi
    docker volume rm "$VOLUME" >/dev/null 2>&1 || true
    if [ -r "$SECRETS" ]; then
      rm -f "$SECRETS"
      rmdir "$PRIVATE_HOME" >/dev/null 2>&1 || true
    fi
    ;;
  status)
    if [ -r "$SECRETS" ]; then
      bootstrap
      docker compose -f "$COMPOSE" ps
    fi
    tailscale serve status | grep -A1 ':8444' || true
    ;;
  *)
    echo "Usage: $0 start|stop|status"; exit 2 ;;
esac
